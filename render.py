#!/usr/bin/env python3
"""Render the approved newspaper using local story data and DejaVu fonts.

The fixed geometry preserves the approved image. No network, clock, or
randomness is used in rendering.
"""

import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / "entry.png"
WIDTH = HEIGHT = 1024
MARGIN = 30
FRAME = 14
GUTTER = 22
COLUMN_WIDTH = (WIDTH - 2 * MARGIN - 2 * GUTTER) // 3
STORY_SIZE = 11.5
STORY_STEP = int(STORY_SIZE * 1.26)
PAPER = (251, 248, 241)
INK = (17, 17, 17)
RED = (185, 28, 28)
GRAY = (107, 114, 128)
LIGHT = (205, 200, 188)
FONT_DIRECTORY = Path("/usr/share/fonts/truetype/dejavu")
COLUMNS = (
    ("NORTH AMERICA", "EUROPE"),
    ("MIDDLE EAST", "AFRICA"),
    ("LATIN AMERICA", "ASIA-PACIFIC", "WORLD"),
)
FOOTER = (
    "All stories dated 26 November 2026  ·  Unconfirmed reports are labelled CLAIM"
    "  ·  Image generated by code — no AI imagery"
)


def font(face, size):
    return ImageFont.truetype(str(FONT_DIRECTORY / (face + ".ttf")), size)


def wrapped_lines(draw, text, typeface):
    lines = []
    current = ""
    for word in text.split():
        candidate = (current + " " + word).strip()
        if draw.textlength(candidate, font=typeface) <= COLUMN_WIDTH:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def centered_text(draw, y, text, typeface, color=INK):
    left = (WIDTH - draw.textlength(text, font=typeface)) / 2
    draw.text((left, y), text, font=typeface, fill=color)


def page_rule(draw, y, width=1):
    draw.line([(MARGIN, y), (WIDTH - MARGIN, y)], fill=INK, width=width)


def draw_masthead(draw, data):
    y = MARGIN + 4
    centered_text(draw, y, data["title"], font("DejaVuSerif-Bold", 62))
    y += 74
    centered_text(draw, y, "THURSDAY  ·  26 NOVEMBER 2026", font("DejaVuSans-Bold", 15))
    y += 24
    count = len(data["leads"]) + sum(len(s["stories"]) for s in data["sections"])
    centered_text(
        draw, y,
        f"ONE DAY IN WORLD NEWS  —  {count} STORIES  ·  7 REGIONS  ·  ALL SOURCED",
        font("DejaVuSans", 11), GRAY,
    )
    y += 22
    page_rule(draw, y, width=3)
    return y + 12


def draw_leads(draw, y, leads):
    draw.text((MARGIN, y), "TOP STORIES", font=font("DejaVuSans-Bold", 12), fill=RED)
    top = y + 20
    kicker_font = font("DejaVuSans-Bold", 11)
    headline_font = font("DejaVuSerif-Bold", 19)
    deck_font = font("DejaVuSans", 12)
    source_font = font("DejaVuSans", 10)
    tag_font = font("DejaVuSans-Bold", 10)
    headline_step = int(19 * 1.25)
    deck_step = int(12 * 1.35)
    layouts = []
    for lead in leads:
        headlines = wrapped_lines(draw, lead["headline"], headline_font)[:3]
        decks = wrapped_lines(draw, lead["deck"], deck_font)[:2]
        height = 16 + (18 if lead["claim"] else 0)
        height += len(headlines) * headline_step + 3
        height += len(decks) * deck_step + 2 + 14
        layouts.append((headlines, decks, height))
    tallest = max(layout[2] for layout in layouts)

    for index, (lead, layout) in enumerate(zip(leads, layouts)):
        headlines, decks, _ = layout
        x = MARGIN + index * (COLUMN_WIDTH + GUTTER)
        cursor = top
        draw.text((x, cursor), lead["kicker"], font=kicker_font, fill=RED)
        cursor += 16
        if lead["claim"]:
            tag = "  CLAIM  "
            tag_width = draw.textlength(tag, font=tag_font)
            draw.rectangle([x, cursor + 2, x + tag_width, cursor + 14], fill=RED)
            draw.text((x, cursor + 2), tag, font=tag_font, fill=(255, 255, 255))
            cursor += 18
        for line in headlines:
            draw.text((x, cursor), line, font=headline_font, fill=INK)
            cursor += headline_step
        cursor += 3
        for line in decks:
            draw.text((x, cursor), line, font=deck_font, fill=INK)
            cursor += deck_step
        cursor += 2
        draw.text((x, cursor), "Source: " + lead["source"], font=source_font, fill=GRAY)
        if index < 2:
            divider_x = x + COLUMN_WIDTH + GUTTER // 2
            draw.line([(divider_x, top), (divider_x, top + tallest)], fill=LIGHT, width=1)
    bottom = top + tallest + 10
    page_rule(draw, bottom)
    return bottom + 12


def draw_story(draw, x, y, story, headline_font, source_font):
    prefix = "[CLAIM] " if story["claim"] else ""
    lines = wrapped_lines(draw, prefix + story["headline"], headline_font)[:2]
    for index, line in enumerate(lines):
        if index == 0 and story["claim"]:
            prefix_width = draw.textlength(prefix, font=headline_font)
            draw.text((x, y), prefix, font=headline_font, fill=RED)
            draw.text((x + prefix_width, y), line[len(prefix):], font=headline_font, fill=INK)
        else:
            draw.text((x, y), line, font=headline_font, fill=INK)
        y += STORY_STEP
    source = "— " + story["source"]
    last_width = draw.textlength(lines[-1], font=headline_font) if lines else 0
    source_width = draw.textlength(source, font=source_font)
    if last_width + 6 + source_width <= COLUMN_WIDTH:
        draw.text(
            (x + last_width + 6, y - STORY_STEP + 2), source,
            font=source_font, fill=GRAY,
        )
    else:
        draw.text((x, y), source, font=source_font, fill=GRAY)
        y += int(10 * 1.3)
    return y + 4


def draw_regions(draw, top, sections):
    stories_by_name = {section["name"]: section["stories"] for section in sections}
    headline_font = font("DejaVuSans-Bold", STORY_SIZE)
    section_font = font("DejaVuSans-Bold", 12)
    source_font = font("DejaVuSans", 10)
    column_bottoms = []
    for index, names in enumerate(COLUMNS):
        x = MARGIN + index * (COLUMN_WIDTH + GUTTER)
        y = top
        for name in names:
            stories = stories_by_name.get(name, [])
            draw.text((x, y), name, font=section_font, fill=RED)
            count = str(len(stories))
            count_width = draw.textlength(count, font=section_font)
            draw.text((x + COLUMN_WIDTH - count_width, y), count, font=section_font, fill=GRAY)
            y += 16
            draw.line([(x, y), (x + COLUMN_WIDTH, y)], fill=INK, width=1)
            y += 8
            for story in stories:
                y = draw_story(draw, x, y, story, headline_font, source_font)
            y += 6
        column_bottoms.append(y)
    return max(column_bottoms) + 4


def render(data):
    image = Image.new("RGB", (WIDTH, HEIGHT), PAPER)
    draw = ImageDraw.Draw(image)
    draw.rectangle(
        [FRAME, FRAME, WIDTH - FRAME - 1, HEIGHT - FRAME - 1], outline=INK, width=2
    )
    y = draw_masthead(draw, data)
    y = draw_leads(draw, y, data["leads"])
    y = draw_regions(draw, y, data["sections"])
    page_rule(draw, y)
    centered_text(draw, y + 8, FOOTER, font("DejaVuSans", 10), GRAY)
    return image


def main():
    data = json.loads((ROOT / "stories.json").read_text(encoding="utf-8"))
    image = render(data)
    image.save(OUTPUT, format="PNG", optimize=True)
    encoded = OUTPUT.read_bytes()
    print(f"wrote {OUTPUT}")
    print(f"size_bytes={len(encoded)} limit=1048576 ok={len(encoded) <= 1048576}")
    print(f"dimensions={image.size}")
    print(f"story_font={STORY_SIZE}")
    print(f"sha256={hashlib.sha256(encoded).hexdigest()}")


if __name__ == "__main__":
    main()
