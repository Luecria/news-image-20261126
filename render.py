#!/usr/bin/env python3
"""Measure, fit, and justify a newspaper from local JSON and DejaVu fonts.

Rendering uses no network, timestamps, or randomness. Fixed masthead, lead,
section-heading, source, and footer styling preserves the approved identity.
"""

import hashlib
import json
from functools import lru_cache
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parent
OUTPUT = ROOT / 'entry.png'
WIDTH = HEIGHT = 1024
MARGIN, FRAME, GUTTER = 30, 14, 22
COLUMN_WIDTH = (WIDTH - 2 * MARGIN - 2 * GUTTER) // 3
FONT_DIRECTORY = Path('/usr/share/fonts/truetype/dejavu')
STORY_SIZES = (13, 12.75, 12.5, 12.25, 12, 11.75, 11.5, 11.25, 11)
STORY_GAP = 2
FOOTER_RULE_Y = 947
COLUMN_END_Y = FOOTER_RULE_Y - 8
PAPER = (251, 248, 241)
INK = (17, 17, 17)
RED = (185, 28, 28)
GRAY = (107, 114, 128)
LIGHT = (205, 200, 188)
COLUMNS = (
    ('NORTH AMERICA', 'EUROPE'),
    ('MIDDLE EAST', 'AFRICA'),
    ('LATIN AMERICA', 'ASIA-PACIFIC', 'WORLD'),
)
FOOTER = (
    'All stories dated 26 November 2026  ·  Unconfirmed reports are labelled CLAIM'
    '  ·  Image generated by code — no AI imagery'
)


@lru_cache(maxsize=None)
def font(face, size):
    return ImageFont.truetype(str(FONT_DIRECTORY / (face + '.ttf')), size)


def wrap(draw, text, typeface):
    """Wrap without dropping words or silently truncating story headlines."""
    lines, current = [], ''
    for word in text.split():
        if draw.textlength(word, font=typeface) > COLUMN_WIDTH:
            raise ValueError(f'Word exceeds the column width: {word!r}')
        candidate = f'{current} {word}'.strip()
        if current and draw.textlength(candidate, font=typeface) > COLUMN_WIDTH:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines


class Page:
    """Retain each drawn text run and its ink bounds for layout validation."""

    def __init__(self):
        self.image = Image.new('RGB', (WIDTH, HEIGHT), PAPER)
        self.draw = ImageDraw.Draw(self.image)
        self.text_boxes = []

    def text(self, x, y, value, typeface, color=INK, role='fixed'):
        # Trailing spaces advance the pen but contain no ink.
        box = self.draw.textbbox((x, y), value.rstrip(), font=typeface)
        self.text_boxes.append({'text': value, 'box': box, 'role': role})
        self.draw.text((x, y), value, font=typeface, fill=color)

    def centered(self, y, value, typeface, color=INK):
        x = (WIDTH - self.draw.textlength(value, font=typeface)) / 2
        self.text(x, y, value, typeface, color)

    def rule(self, y, width=1):
        self.draw.line(((MARGIN, y), (WIDTH - MARGIN, y)), fill=INK, width=width)


def masthead(page, data):
    y = MARGIN + 4
    page.centered(y, data['title'], font('DejaVuSerif-Bold', 62))
    y += 74
    page.centered(y, 'THURSDAY  ·  26 NOVEMBER 2026', font('DejaVuSans-Bold', 15))
    y += 24
    count = len(data['leads']) + sum(len(s['stories']) for s in data['sections'])
    page.centered(
        y, f'ONE DAY IN WORLD NEWS  —  {count} STORIES  ·  7 REGIONS  ·  ALL SOURCED',
        font('DejaVuSans', 11), GRAY,
    )
    y += 22
    page.rule(y, 3)
    return y + 12


def leads(page, y, items):
    """Keep the approved lead block's typography, geometry, and line limits."""
    page.text(MARGIN, y, 'TOP STORIES', font('DejaVuSans-Bold', 12), RED)
    top = y + 20
    kicker_font = font('DejaVuSans-Bold', 11)
    headline_font = font('DejaVuSerif-Bold', 19)
    deck_font = font('DejaVuSans', 12)
    source_font = font('DejaVuSans', 10)
    tag_font = font('DejaVuSans-Bold', 10)
    layouts = []
    for item in items:
        headlines = wrap(page.draw, item['headline'], headline_font)[:3]
        decks = wrap(page.draw, item['deck'], deck_font)[:2]
        height = 16 + (18 if item['claim'] else 0)
        height += len(headlines) * 23 + 3 + len(decks) * 16 + 2 + 14
        layouts.append((headlines, decks, height))
    tallest = max(layout[2] for layout in layouts)
    for index, (item, layout) in enumerate(zip(items, layouts)):
        headlines, decks, _ = layout
        x = MARGIN + index * (COLUMN_WIDTH + GUTTER)
        cursor = top
        page.text(x, cursor, item['kicker'], kicker_font, RED)
        cursor += 16
        if item['claim']:
            tag = '  CLAIM  '
            tag_width = page.draw.textlength(tag, font=tag_font)
            page.draw.rectangle((x, cursor + 2, x + tag_width, cursor + 14), fill=RED)
            page.text(x, cursor + 2, tag, tag_font, (255, 255, 255), 'claim-tag')
            cursor += 18
        for line in headlines:
            page.text(x, cursor, line, headline_font)
            cursor += 23
        cursor += 3
        for line in decks:
            page.text(x, cursor, line, deck_font)
            cursor += 16
        cursor += 2
        page.text(x, cursor, 'Source: ' + item['source'], source_font, GRAY)
        if index < 2:
            divider = x + COLUMN_WIDTH + GUTTER // 2
            page.draw.line(((divider, top), (divider, top + tallest)), fill=LIGHT)
    bottom = top + tallest + 10
    page.rule(bottom)
    return bottom + 12


def story_layout(draw, item, size):
    headline_font = font('DejaVuSans-Bold', size)
    source_font = font('DejaVuSans', 10)
    prefix = '[CLAIM] ' if item['claim'] else ''
    lines = wrap(draw, prefix + item['headline'], headline_font)
    step = int(size * 1.26)
    source = '— ' + item['source']
    last_width = draw.textlength(lines[-1], font=headline_font)
    inline = last_width + 6 + draw.textlength(source, font=source_font) <= COLUMN_WIDTH
    source_x = last_width + 6 if inline else 0
    source_y = (len(lines) - 1) * step + 2 if inline else len(lines) * step
    advance = len(lines) * step + (0 if inline else 13)
    bounds = [draw.textbbox((0, i * step), line, font=headline_font)
              for i, line in enumerate(lines)]
    bounds.append(draw.textbbox((source_x, source_y), source, font=source_font))
    return {'item': item, 'lines': lines, 'prefix': prefix, 'step': step,
            'source': source, 'source_x': source_x, 'source_y': source_y,
            'advance': advance, 'ink_bottom': max(b[3] for b in bounds)}


def column_layout(draw, sections, names, size):
    elements, y, count = [], 0, 0
    for name in names:
        items = sections[name]
        elements.append({'kind': 'section', 'name': name, 'count': len(items), 'y': y})
        y += 24
        for item in items:
            story = story_layout(draw, item, size)
            elements.append({'kind': 'story', 'y': y, **story})
            count += 1
            ink_bottom = y + story['ink_bottom']
            y += story['advance'] + STORY_GAP
        y += 6
    return {'elements': elements, 'count': count, 'height': ink_bottom}


def choose_layout(page, top, data):
    sections = {section['name']: section['stories'] for section in data['sections']}
    assert set(sections) == {name for names in COLUMNS for name in names}
    available = COLUMN_END_Y - top
    attempts = []
    for size in STORY_SIZES:
        columns = [column_layout(page.draw, sections, names, size) for names in COLUMNS]
        heights = [column['height'] for column in columns]
        attempts.append({'font': size, 'heights': heights})
        if max(heights) <= available:
            return size, columns, attempts
    raise ValueError(f'Stories do not fit at the 11pt minimum: {attempts}')


def regions(page, top, data):
    size, columns, attempts = choose_layout(page, top, data)
    headline_font = font('DejaVuSans-Bold', size)
    source_font = font('DejaVuSans', 10)
    section_font = font('DejaVuSans-Bold', 12)
    tallest = max(column['height'] for column in columns)
    shared_slack = COLUMN_END_Y - top - tallest
    report = []
    for index, column in enumerate(columns):
        # Equalize shorter columns, then distribute the remaining common slack.
        # Every inter-story interval in a column receives the same extra gap.
        slack = shared_slack + tallest - column['height']
        extra_gap = slack / (column['count'] - 1)
        x = MARGIN + index * (COLUMN_WIDTH + GUTTER)
        seen, boxes = 0, []
        for element in column['elements']:
            y = top + element['y'] + min(seen, column['count'] - 1) * extra_gap
            if element['kind'] == 'section':
                page.text(x, y, element['name'], section_font, RED, 'section')
                count = str(element['count'])
                count_x = x + COLUMN_WIDTH - page.draw.textlength(count, font=section_font)
                page.text(count_x, y, count, section_font, GRAY, 'section-count')
                page.draw.line(((x, y + 16), (x + COLUMN_WIDTH, y + 16)), fill=INK)
                continue
            start = len(page.text_boxes)
            for line_index, line in enumerate(element['lines']):
                line_y = y + line_index * element['step']
                if line_index == 0 and element['prefix']:
                    prefix = element['prefix']
                    prefix_width = page.draw.textlength(prefix, font=headline_font)
                    page.text(x, line_y, prefix, headline_font, RED, 'story-claim')
                    page.text(x + prefix_width, line_y, line[len(prefix):], headline_font,
                              role='story-headline')
                else:
                    page.text(x, line_y, line, headline_font, role='story-headline')
            page.text(x + element['source_x'], y + element['source_y'],
                      element['source'], source_font, GRAY, 'story-source')
            story_boxes = page.text_boxes[start:]
            boxes.extend(story_boxes)
            # DejaVu's capital J has a one-pixel left overhang.
            assert all(x - 1 <= b['box'][0] and b['box'][2] <= x + COLUMN_WIDTH
                       for b in story_boxes), 'Story crosses its column edge'
            seen += 1
        bottom = max(b['box'][3] for b in boxes)
        assert abs(bottom - COLUMN_END_Y) < 0.01
        report.append({'sections': list(COLUMNS[index]), 'stories': seen,
                       'natural_height': column['height'], 'extra_gap': extra_gap,
                       'ink_bottom': bottom, 'footer_gap': FOOTER_RULE_Y - bottom})
    return size, report, attempts


def render(data):
    page = Page()
    page.draw.rectangle((FRAME, FRAME, WIDTH - FRAME - 1, HEIGHT - FRAME - 1),
                        outline=INK, width=2)
    top = leads(page, masthead(page, data), data['leads'])
    size, columns, attempts = regions(page, top, data)
    page.rule(FOOTER_RULE_Y)
    page.centered(FOOTER_RULE_Y + 8, FOOTER, font('DejaVuSans', 10), GRAY)
    for item in page.text_boxes:
        left, upper, right, lower = item['box']
        assert FRAME < left <= right < WIDTH - FRAME
        assert FRAME < upper <= lower < HEIGHT - FRAME
    # Text boxes may touch, but distinct text runs must not overlap in area.
    for index, first in enumerate(page.text_boxes):
        a = first['box']
        for second in page.text_boxes[index + 1:]:
            b = second['box']
            assert not (min(a[2], b[2]) > max(a[0], b[0]) and
                        min(a[3], b[3]) > max(a[1], b[1])), (first, second)
    report = {'story_font': size, 'regions_top': top, 'footer_rule': FOOTER_RULE_Y,
              'columns': columns, 'font_attempts': attempts,
              'stories': len(data['leads']) + sum(len(s['stories']) for s in data['sections']),
              'claim_labels': sum(bool(s['claim']) for s in data['leads']) +
              sum(bool(s['claim']) for region in data['sections'] for s in region['stories'])}
    return page.image, report


def main():
    data = json.loads((ROOT / 'stories.json').read_text(encoding='utf-8'))
    image, report = render(data)
    image.save(OUTPUT, format='PNG', optimize=True)
    encoded = OUTPUT.read_bytes()
    assert image.size == (1024, 1024) and len(encoded) <= 1048576
    report.update({'size_bytes': len(encoded), 'dimensions': list(image.size),
                   'sha256': hashlib.sha256(encoded).hexdigest()})
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
